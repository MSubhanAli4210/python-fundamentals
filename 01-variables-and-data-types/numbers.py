"""Basic examples of Python numbers and arithmetic."""

whole_number = 12
decimal_number = 3.5

print("Integer:", whole_number)
print("Float:", decimal_number)
print("Addition:", whole_number + decimal_number)
print("Subtraction:", whole_number - decimal_number)
print("Multiplication:", whole_number * decimal_number)
print("Division:", whole_number / 2)
print("Floor division:", whole_number // 5)
print("Remainder:", whole_number % 5)
print("Power:", 2**3)

# Convert between numeric types.
print("Integer from float:", int(decimal_number))
print("Float from integer:", float(whole_number))