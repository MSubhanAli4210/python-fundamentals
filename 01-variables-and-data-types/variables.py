
# Python Fundamentals: Variables

# 1. Storing values in variables
name = "Subhan"
age = 21
height = 5.8
is_student = True

# 2. Printing variables
print("Name:", name)
print("Age:", age)
print("Height:", height)
print("Is student:", is_student)

# 3. Checking data types
print(type(name))
print(type(age))
print(type(height))
print(type(is_student))

# 4. Updating variables
age = 22
print("Updated age:", age)

# 5. Assigning multiple variables
x, y, z = 10, 20, 30
print("x =", x)
print("y =", y)
print("z =", z)

# 6. Assigning the same value
a = b = c = 100
print(a, b, c)
